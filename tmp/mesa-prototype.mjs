import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {PDFDocument,rgb,degrees} from 'pdf-lib';
import fontkit from '@pdf-lib/fontkit';
import qrcode from 'qrcode-generator';
const dest='C:/Users/anham/Desktop/Screepts/Fotos/A4 sem categorias';
await mkdir(dest,{recursive:true});
const mm=72/25.4,W=210*mm,H=297*mm,tab=30*mm,face=118.5*mm;
const doc=await PDFDocument.create();doc.registerFontkit(fontkit);
const font=await doc.embedFont(await readFile('assets/fonts/noto-serif-latin-400-normal.woff'),{subset:true});
const page=doc.addPage([W,H]);
const cream=rgb(.985,.970,.935),green=rgb(.12,.22,.15),gold=rgb(.66,.46,.16),grey=rgb(.48,.48,.45);
page.drawRectangle({x:0,y:tab,width:W,height:2*face,color:cream});
const image=await doc.embedPng(await readFile(dest+'/Imagens/Mesa 01.png'));
const scale=Math.min((W-8*mm)/image.width,(face-4*mm)/image.height);
const iw=image.width*scale,ih=image.height*scale;
page.drawImage(image,{x:(W+iw)/2,y:tab+face+(face+ih)/2,width:iw,height:ih,rotate:degrees(180)});
const center=(s,y,size,color=green)=>page.drawText(s,{x:(W-font.widthOfTextAtSize(s,size))/2,y,size,font,color});
center('Mesa 1',tab+face-23*mm,18,gold);
page.drawLine({start:{x:W/2-25*mm,y:tab+face-31*mm},end:{x:W/2+25*mm,y:tab+face-31*mm},thickness:.8,color:gold});
['O amor floresce','onde as raízes','são família.'].forEach((line,i)=>center(line,tab+face-51*mm-i*15*mm,32));
const link='https://casamento.purruma.com/mensagem/categoria/1';
const qr=qrcode(0,'M');qr.addData(link);qr.make();
const side=28*mm,count=qr.getModuleCount(),cell=side/(count+8),qx=8*mm,qy=tab+10*mm;
page.drawRectangle({x:qx,y:qy,width:side,height:side,color:rgb(1,1,1)});
for(let r=0;r<count;r++)for(let c=0;c<count;c++)if(qr.isDark(r,c))page.drawRectangle({x:qx+(c+4)*cell,y:qy+side-(r+5)*cell,width:cell+.01,height:cell+.01,color:rgb(0,0,0)});
const linkLabel=link;
page.drawText(linkLabel,{x:qx,y:tab+6*mm,size:7,font,color:grey});
const annotation=doc.context.register(doc.context.obj({Type:'Annot',Subtype:'Link',Rect:[qx,tab+5*mm,qx+Math.max(side,font.widthOfTextAtSize(linkLabel,7)),qy+side],Border:[0,0,0],A:{Type:'Action',S:'URI',URI:link}}));
page.node.addAnnot(annotation);
const credit='by purruma.com';
page.drawText(credit,{x:W-8*mm-font.widthOfTextAtSize(credit,7),y:tab+6*mm,size:7,font,color:grey});
for(const y of [tab,H/2,H-tab])page.drawLine({start:{x:4*mm,y},end:{x:W-4*mm,y},thickness:.5,dashArray:[3,4],color:grey});
center('ABA DA BASE - dobrar para dentro',tab/2+4,9,grey);
center('Sobrepor as abas e fixar com fita ou cola.',tab/2-11,8,grey);
center('ABA DA BASE - dobrar para dentro',H-tab/2,9,grey);
doc.setTitle('Mesa 1 - Expositor triangular A4 - Prova');
await writeFile(dest+'/Mesa 1 - Prova A4 QR no canto.pdf',await doc.save());
console.log('PDF A4: 210 x 297 mm. Dobras a 30, 148.5 e 267 mm do topo.');
